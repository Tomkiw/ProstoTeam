const NBSP = ' ';

// Однолітерне слово (в, у, з, і, й, а, о / w, z, i, o, a, u…) — на початку тексту, після пробілу чи лапок.
// Lookbehind дивиться на вихідний рядок, тож «а й сайт» склеюється повністю: «а␣й␣сайт»
const SHORT_WORD = /(?<=^|[\s («„"])(\p{L})\s+(?=\S)/gu;
const DASH = /\s+—/g;

/**
 * Типографіка для української й польської: однолітерні слова не лишаються в кінці рядка
 * («висячі» прийменники й сполучники), а тире не переноситься на початок наступного.
 */
export function bindShortWords(text: string): string {
  return text.replace(SHORT_WORD, `$1${NBSP}`).replace(DASH, `${NBSP}—`);
}
